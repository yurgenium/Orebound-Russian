def L(rect, text, size, style, **kw):
    d = dict(rect=rect, size=size, style=style)
    if isinstance(text, list):
        d['lines'] = text
    else:
        d['text'] = text
    d.update(kw)
    return d


def head(title, sub, w):
    return [L([36, 14, w - 34, 73], title, 44, 'title'), L([36, 73, w - 34, 104], sub, 26, 'sub')]


def shot(title, sub):
    return [L([40, 10, 1878, 89], title, 62, 'title'), L([40, 89, 1878, 145], sub, 40, 'sub')]


def legend(x0, x1, ys, texts):
    return [L([x0, y, x1, y + 47], t, 28, 'text') for y, t in zip(ys, texts)]


